"""Startup state reconciliation against Binance USD(S)-M Futures exchange state.

Validates the 6 startup reconciliation matrix cases:
1. Clean startup: Exchange 0 positions, Local DB 0 positions, 0 open orders.
2. Matching open position: Exchange 1 position, Local DB matches, SL/TP verified -> recover state.
3. Orphaned open orders: Exchange 0 positions, bot-generated open orders present -> cancel orders.
4. Unprotected open position: Exchange 1 position, SL or TP missing -> emergency market close.
5. Position closed while offline: Local DB has open position, Exchange 0 positions -> close local DB.
6. Multiple open positions: Exchange > 1 open positions -> safety violation (ReconciliationError).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
import time
from typing import TYPE_CHECKING, List, Optional
from src.exchange.client import BinanceFuturesClient
from src.execution.client_id import OrderPrefix, is_bot_client_order_id
from src.execution.models import OrderSide
from src.monitoring.logger import get_logger
from src.positions.models import Position, PositionState, ProtectiveOrderPair
from src.positions.protective import ProtectiveOrderManager
from src.state.repository import StateRepository

if TYPE_CHECKING:
  from src.positions.manager import PositionManager

logger = get_logger("state.reconciler")


class ReconciliationStatus(str, Enum):
  """Outcome classifications for startup reconciliation."""

  CLEAN = "CLEAN"
  POSITION_RECOVERED = "POSITION_RECOVERED"
  ORPHANED_ORDERS_CLEARED = "ORPHANED_ORDERS_CLEARED"
  UNPROTECTED_EMERGENCY_CLOSE = "UNPROTECTED_EMERGENCY_CLOSE"
  CLOSED_WHILE_OFFLINE = "CLOSED_WHILE_OFFLINE"
  MULTIPLE_POSITIONS_ERROR = "MULTIPLE_POSITIONS_ERROR"


class ReconciliationError(Exception):
  """Raised when exchange state violates fundamental safety invariants during startup."""


@dataclass
class ReconciliationReport:
  """Detailed report generated by StartupReconciler."""

  status: ReconciliationStatus
  details: str
  recovered_position: Optional[Position] = None
  cancelled_order_ids: List[str] = field(default_factory=list)
  emergency_closed: bool = False
  timestamp_ms: int = 0


class StartupReconciler:
  """Reconciles persistent local database state against live exchange positions and orders."""

  def __init__(
      self,
      exchange_client: BinanceFuturesClient,
      repository: StateRepository,
      protective_manager: ProtectiveOrderManager,
      position_manager: PositionManager,
  ):
    self.client = exchange_client
    self.repository = repository
    self.protective_manager = protective_manager
    self.position_manager = position_manager

  async def reconcile_startup_state(self) -> ReconciliationReport:
    """Executes the startup state reconciliation matrix.

    Returns:
        ReconciliationReport: Audit and diagnostic report of actions taken.

    Raises:
        ReconciliationError: If multiple open positions exist on the exchange.
    """
    logger.info("Initiating startup state reconciliation against exchange...")

    # 1. Query live exchange state
    all_positions = await self.client.get_positions()
    open_positions = [p for p in all_positions if p.is_open]
    open_orders = await self.client.get_open_orders()
    local_open_pos = self.repository.get_open_position()

    now_ms = int(time.time() * 1000)

    logger.info(
        "Reconciliation state queried: exchange_open_pos=%d, exchange_orders=%d, local_open_pos=%s",
        len(open_positions),
        len(open_orders),
        local_open_pos.position_id if local_open_pos else "None",
    )

    # --------------------------------------------------------------------------
    # Case 6: Multiple open positions on exchange (Fatal Safety Violation)
    # --------------------------------------------------------------------------
    if len(open_positions) > 1:
      symbols = [p.symbol for p in open_positions]
      logger.critical(
          "SAFETY VIOLATION: Multiple open positions detected on exchange: %s",
          symbols,
      )
      self.repository.log_audit(
          "RECONCILE_FATAL_ERROR",
          "EXCHANGE",
          "STARTUP",
          f"Multiple open positions detected: {symbols}",
      )
      raise ReconciliationError(
          f"Safety violation: multiple open positions detected on exchange: {symbols}"
      )

    # --------------------------------------------------------------------------
    # Case 1: Clean Startup (0 positions, 0 orders, 0 local)
    # --------------------------------------------------------------------------
    if (
        len(open_positions) == 0
        and local_open_pos is None
        and len(open_orders) == 0
    ):
      logger.info("Reconciliation complete: Clean startup state.")
      return ReconciliationReport(
          status=ReconciliationStatus.CLEAN,
          details="Clean startup: no open positions or orders on exchange or database.",
          timestamp_ms=now_ms,
      )

    # --------------------------------------------------------------------------
    # Case 5: Position closed on exchange while offline
    # --------------------------------------------------------------------------
    if len(open_positions) == 0 and local_open_pos is not None:
      logger.warning(
          "Position %s (%s) was closed on exchange while bot was offline. Updating database...",
          local_open_pos.position_id,
          local_open_pos.symbol,
      )
      # Cancel any leftover bot orders
      cancelled_ids: List[str] = []
      for o in open_orders:
        if is_bot_client_order_id(o.client_order_id):
          try:
            await self.client.cancel_order(
                o.symbol, client_order_id=o.client_order_id
            )
            cancelled_ids.append(o.client_order_id)
          except Exception as exc:
            logger.warning(
                "Error cancelling leftover order %s: %s",
                o.client_order_id,
                exc,
            )

      self.repository.close_position(
          position_id=local_open_pos.position_id,
          exit_price=local_open_pos.entry_price,
          realized_pnl=0.0,
          exit_reason="CLOSED_WHILE_OFFLINE",
          closed_at=now_ms,
      )
      self.repository.log_audit(
          "RECONCILE_CLOSED_WHILE_OFFLINE",
          "POSITION",
          local_open_pos.position_id,
          f"Closed offline. Cancelled {len(cancelled_ids)} leftover orders.",
      )
      return ReconciliationReport(
          status=ReconciliationStatus.CLOSED_WHILE_OFFLINE,
          details=f"Position {local_open_pos.position_id} closed while offline. Cancelled {len(cancelled_ids)} leftover orders.",
          cancelled_order_ids=cancelled_ids,
          timestamp_ms=now_ms,
      )

    # --------------------------------------------------------------------------
    # Case 3: Orphaned orders on exchange with no open position
    # --------------------------------------------------------------------------
    if len(open_positions) == 0 and len(open_orders) > 0:
      logger.warning(
          "Orphaned open orders detected on exchange with zero positions. Cleaning up..."
      )
      cancelled_ids = []
      for o in open_orders:
        if is_bot_client_order_id(o.client_order_id):
          try:
            await self.client.cancel_order(
                o.symbol, client_order_id=o.client_order_id
            )
            cancelled_ids.append(o.client_order_id)
          except Exception as exc:
            logger.warning(
                "Error cancelling orphaned order %s: %s",
                o.client_order_id,
                exc,
            )

      self.repository.log_audit(
          "RECONCILE_ORPHANED_ORDERS_CLEARED",
          "EXCHANGE",
          "STARTUP",
          f"Cancelled {len(cancelled_ids)} orphaned bot orders.",
      )
      return ReconciliationReport(
          status=ReconciliationStatus.ORPHANED_ORDERS_CLEARED,
          details=f"Cleared {len(cancelled_ids)} orphaned bot orders from exchange.",
          cancelled_order_ids=cancelled_ids,
          timestamp_ms=now_ms,
      )

    # --------------------------------------------------------------------------
    # From here, len(open_positions) == 1
    # --------------------------------------------------------------------------
    ex_pos = open_positions[0]
    sym_orders = [o for o in open_orders if o.symbol == ex_pos.symbol]

    sl_order = None
    tp_order = None
    for o in sym_orders:
      if o.order_type == "STOP_MARKET" or o.client_order_id.startswith(
          OrderPrefix.STOP_LOSS.value
      ):
        sl_order = o
      elif o.order_type == "TAKE_PROFIT_MARKET" or o.client_order_id.startswith(
          OrderPrefix.TAKE_PROFIT.value
      ):
        tp_order = o

    # --------------------------------------------------------------------------
    # Case 2: Matching open position with active SL and TP protection
    # --------------------------------------------------------------------------
    if (
        sl_order is not None
        and tp_order is not None
        and local_open_pos is not None
        and local_open_pos.symbol == ex_pos.symbol
    ):
      logger.info(
          "Matching open position found for %s with verified SL (%s) and TP (%s). Re-hydrating...",
          ex_pos.symbol,
          sl_order.client_order_id,
          tp_order.client_order_id,
      )
      entry_side = OrderSide.BUY if ex_pos.position_amt > 0 else OrderSide.SELL
      exit_side = (
          OrderSide.SELL if entry_side == OrderSide.BUY else OrderSide.BUY
      )

      pair = ProtectiveOrderPair(
          symbol=ex_pos.symbol,
          entry_side=entry_side,
          exit_side=exit_side,
          quantity=abs(ex_pos.position_amt),
          avg_entry_price=ex_pos.entry_price,
          sl_order_id=sl_order.order_id,
          sl_client_order_id=sl_order.client_order_id,
          sl_price=sl_order.stop_price,
          tp_order_id=tp_order.order_id,
          tp_client_order_id=tp_order.client_order_id,
          tp_price=tp_order.stop_price,
          is_active=True,
      )

      async with self.protective_manager._lock:
        self.protective_manager._active_pairs[ex_pos.symbol] = pair

      recovered_pos = Position(
          position_id=local_open_pos.position_id,
          symbol=ex_pos.symbol,
          side=entry_side,
          status=PositionState.OPEN,
          quantity=abs(ex_pos.position_amt),
          entry_price=ex_pos.entry_price,
          leverage=ex_pos.leverage,
          stop_loss_price=pair.sl_price,
          take_profit_price=pair.tp_price,
          created_at=local_open_pos.created_at,
          updated_at=now_ms,
          protective_pair=pair,
      )
      self.position_manager.set_current_position(recovered_pos)

      self.repository.log_audit(
          "RECONCILE_POSITION_RECOVERED",
          "POSITION",
          local_open_pos.position_id,
          f"Recovered {ex_pos.symbol} position with SL {pair.sl_price} and TP {pair.tp_price}",
      )
      return ReconciliationReport(
          status=ReconciliationStatus.POSITION_RECOVERED,
          details=f"Successfully recovered open position for {ex_pos.symbol}.",
          recovered_position=recovered_pos,
          timestamp_ms=now_ms,
      )

    # --------------------------------------------------------------------------
    # Case 4: Unprotected open position on exchange (Missing SL or TP)
    # --------------------------------------------------------------------------
    logger.critical(
        "UNPROTECTED POSITION DETECTED: Exchange position on %s has missing or invalid protection! Initiating emergency close...",
        ex_pos.symbol,
    )
    entry_side = OrderSide.BUY if ex_pos.position_amt > 0 else OrderSide.SELL
    emg_res = await self.protective_manager.execute_emergency_market_close(
        symbol=ex_pos.symbol,
        position_side=entry_side,
        quantity=abs(ex_pos.position_amt),
    )

    # Cancel any partial protective orders for this symbol
    cancelled_ids = []
    for o in sym_orders:
      if is_bot_client_order_id(o.client_order_id):
        try:
          await self.client.cancel_order(
              o.symbol, client_order_id=o.client_order_id
          )
          cancelled_ids.append(o.client_order_id)
        except Exception as exc:
          logger.warning("Error cancelling order %s: %s", o.client_order_id, exc)

    if local_open_pos:
      self.repository.close_position(
          position_id=local_open_pos.position_id,
          exit_price=ex_pos.entry_price,
          realized_pnl=0.0,
          exit_reason="EMERGENCY_UNPROTECTED",
          closed_at=now_ms,
      )

    self.repository.log_audit(
        "RECONCILE_UNPROTECTED_EMERGENCY_CLOSE",
        "EXCHANGE",
        ex_pos.symbol,
        f"Emergency closed unprotected position. Result closed={emg_res.is_closed}",
    )
    return ReconciliationReport(
        status=ReconciliationStatus.UNPROTECTED_EMERGENCY_CLOSE,
        details=f"Unprotected position detected on {ex_pos.symbol}; executed emergency market close.",
        emergency_closed=True,
        cancelled_order_ids=cancelled_ids,
        timestamp_ms=now_ms,
    )
