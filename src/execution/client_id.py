"""Deterministic, collision-resistant clientOrderId generator.

Specification from docs/API_CONTRACTS.md Section 3:
clientOrderId = PREFIX + TIMESTAMP_MS + "_" + RANDOM_HEX
Max length allowed by Binance Futures: 36 characters.

Format Examples:
- Entry:       HA_E_1711234567890_a1f9
- Stop-Loss:   HA_SL_1711234567890_a1f9
- Take-Profit: HA_TP_1711234567890_a1f9
- Emergency:   HA_EMG_1711234567890_a1f9
"""

from enum import Enum
import os
import re
import time
from typing import Optional


class OrderPrefix(str, Enum):
  """Order client ID prefixes for bot identification and recovery."""

  ENTRY = "HA_E"
  STOP_LOSS = "HA_SL"
  TAKE_PROFIT = "HA_TP"
  EMERGENCY = "HA_EMG"


# Maximum clientOrderId length supported by Binance USD(S)-M Futures
MAX_CLIENT_ORDER_ID_LENGTH = 36

# Regex for validating bot-generated clientOrderId
CLIENT_ORDER_ID_REGEX = re.compile(
    r"^(HA_E|HA_SL|HA_TP|HA_EMG)_(\d{13})_([0-9a-fA-F]{4,8})$"
)


def generate_client_order_id(
    prefix: OrderPrefix | str,
    timestamp_ms: Optional[int] = None,
    hex_len: int = 6,
) -> str:
  """Generates a collision-resistant, traceable clientOrderId.

  Args:
      prefix: OrderPrefix enum or string prefix (e.g. OrderPrefix.ENTRY).
      timestamp_ms: Millisecond timestamp (defaults to current time).
      hex_len: Number of random hex characters (default 4 bytes / 4 chars).

  Returns:
      A valid clientOrderId string <= 36 chars.
  """
  pfx = prefix.value if isinstance(prefix, OrderPrefix) else str(prefix)
  ts = timestamp_ms if timestamp_ms is not None else int(time.time() * 1000)
  random_hex = os.urandom((hex_len + 1) // 2).hex()[:hex_len]

  client_id = f"{pfx}_{ts}_{random_hex}"
  if len(client_id) > MAX_CLIENT_ORDER_ID_LENGTH:
    raise ValueError(
        f"Generated clientOrderId '{client_id}' exceeds maximum length "
        f"of {MAX_CLIENT_ORDER_ID_LENGTH} characters."
    )
  return client_id


def is_bot_client_order_id(client_order_id: str) -> bool:
  """Checks whether a clientOrderId was generated by this bot."""
  if not client_order_id:
    return False
  return CLIENT_ORDER_ID_REGEX.match(client_order_id) is not None


def parse_client_order_id(client_order_id: str) -> Optional[dict]:
  """Parses a bot clientOrderId into its prefix, timestamp, and random suffix components.

  Returns:
      Dict with 'prefix', 'timestamp_ms', and 'random_hex' if valid, None otherwise.
  """
  match = CLIENT_ORDER_ID_REGEX.match(client_order_id)
  if not match:
    return None
  prefix_str, ts_str, hex_str = match.groups()
  return {
      "prefix": OrderPrefix(prefix_str),
      "timestamp_ms": int(ts_str),
      "random_hex": hex_str,
  }
